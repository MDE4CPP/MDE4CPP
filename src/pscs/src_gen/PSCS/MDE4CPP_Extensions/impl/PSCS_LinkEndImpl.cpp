void PSCS_LinkEndImpl::saveContent(std::shared_ptr<persistence::interfaces::XSaveHandler> saveHandler) const
{
	try
	{
		std::shared_ptr<PSCS::MDE4CPP_Extensions::MDE4CPP_ExtensionsPackage> package = PSCS::MDE4CPP_Extensions::MDE4CPP_ExtensionsPackage::eInstance();
		// Add attributes
          if ( this->eIsSet(package->getPSCS_LinkEnd_Attribute_kind()) )
          {
			PSCS::Semantics::StructuredClassifiers::CS_LinkKind value = this->getKind();
			std::string literal = "";
			if (value == PSCS::Semantics::StructuredClassifiers::CS_LinkKind::TOENVIRONMENT)
			{
				literal = "ToEnvironment";
			}
			else if (value == PSCS::Semantics::StructuredClassifiers::CS_LinkKind::TOINTERNAL)
			{
				literal = "ToInternal";
			}
			else if (value == PSCS::Semantics::StructuredClassifiers::CS_LinkKind::NONE)
			{
				literal = "None";
			}
			else if (value == PSCS::Semantics::StructuredClassifiers::CS_LinkKind::UNKNOWN)
			{
				literal = "Unknown";
			}
			saveHandler->addAttribute("kind", literal);
          }
	}
	catch (std::exception& e)
	{
		std::cout << "| ERROR    | " << e.what() << std::endl;
	}
}

