#!/usr/bin/env bash
# Linux Bootstrap script for MDE4CPP

set -e

DIR="$( cd "$( dirname "${BASH_SOURCE[0]}" )" && pwd )"
PROJECT_DIR="$( cd "$DIR/../.." && pwd )"
source "$DIR/../common.sh"

PROPS_FILE="$PROJECT_DIR/versions.properties"
load_properties "$PROPS_FILE"

ECLIPSE_DIR="$( cd "$PROJECT_DIR/.." && pwd )/eclipse"
SETENV_FILE="$PROJECT_DIR/setenv.sh"

echo "==========================================================="
echo "MDE4CPP Bootstrap Script for Linux"
echo "==========================================================="

echo "Generating $SETENV_FILE..."
cat << EOF > "$SETENV_FILE"
#!/usr/bin/env bash
# Environment configuration of MDE4CPP
# Generated by bootstrap/linux.sh

# Set MDE4CPP project and eclipse directories
export MDE4CPP_HOME="$PROJECT_DIR"
export MDE4CPP_ECLIPSE_HOME="$ECLIPSE_DIR"

# Set compiler home directory (System default on Linux)
# export COMPILER_HOME=/usr

# Update PATH variable locally
export PATH="\$MDE4CPP_HOME/application/bin:\$MDE4CPP_HOME/application/tools:\$PATH"

# Configure Gradle tasks and compiling processes
export GRADLE_OPTS="-Dorg.gradle.parallel=true"
export ORG_GRADLE_PROJECT_WORKER=1
export ORG_GRADLE_PROJECT_RELEASE=1
export ORG_GRADLE_PROJECT_DEBUG=1
export ORG_GRADLE_PROJECT_DEBUG_MESSAGE_FUML=0

# Configure JAVA CLASSPATH
export CLASSPATH="\$MDE4CPP_ECLIPSE_HOME/plugins"

# Configure compiler delivery name (often auto-detected on Linux)
# export COMPILER_DELIVERY_NAME=linux_gcc

# Set C++ IDE Executable for Gradle task
export CPP_IDE_EXECUTABLE="\$MDE4CPP_ECLIPSE_HOME/eclipse"
EOF
chmod +x "$SETENV_FILE"

echo "==========================================================="
echo "Installing system tools..."
echo "==========================================================="

"$DIR/installJava.sh"
"$DIR/installCompiler.sh"
"$DIR/installCMake.sh"
"$DIR/installEclipse.sh"

echo "==========================================================="
echo "Running Gradle install to download third-party dependencies..."
echo "==========================================================="

# Resolve JAVA_HOME from the installed java version if available
if command -v javac >/dev/null 2>&1; then
    JAVA_HOME="$(dirname "$(dirname "$(readlink -f "$(command -v javac)")")")"
    export JAVA_HOME
    echo "[bootstrap] Using JAVA_HOME=$JAVA_HOME"
else
    echo "[bootstrap] WARNING: javac not found. Gradle might use a fallback Java."
fi

# Load the environment
source "$SETENV_FILE"

cd "$PROJECT_DIR"
GRADLE_WRAPPER="$PROJECT_DIR/application/tools/gradlew"
if [[ -f "$GRADLE_WRAPPER" ]]; then
    # Ensure it's executable
    chmod +x "$GRADLE_WRAPPER"
    "$GRADLE_WRAPPER" install --no-daemon
else
    echo "ERROR: Gradle wrapper not found at $GRADLE_WRAPPER"
    exit 1
fi

echo "==========================================================="
echo "Bootstrap completed successfully!"
echo "To activate the environment, please run:"
echo "  source setenv.sh"
echo "==========================================================="
