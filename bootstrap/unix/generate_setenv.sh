#!/usr/bin/env bash

set -e

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
source "$SCRIPT_DIR/common.sh"

print_header "generate_setenv" "Running Setenv Generator..."

echo "${C_PURPLE}[generate_setenv]${C_WARN} Generating setenv.sh...${C_RESET}"

# DIR is the repository root when calling from bootstrap, so let's deduce it here
REPO_ROOT="$(cd "$SCRIPT_DIR/../.." && pwd)"
PROJECT_DIR="${PROJECT_DIR:-$REPO_ROOT}"
SETENV_FILE="${SETENV_FILE:-$REPO_ROOT/setenv.sh}"
if [[ -n "${MDE4CPP_ECLIPSE_LOCATION:-}" ]]; then
  ECLIPSE_DIR="${MDE4CPP_ECLIPSE_LOCATION}"
else
  ECLIPSE_DIR="${ECLIPSE_DIR:-$REPO_ROOT/../eclipse}"
fi
JAVA_MAJOR="${MDE4CPP_JAVA_VERSION%%.*}"
GCC_MAJOR="${MDE4CPP_COMPILER_VERSION%%.*}"

OS_NAME=$(uname -s)
if [ "$OS_NAME" = "Darwin" ]; then
    OS_DIR="MacOS"
else
    OS_DIR="Linux"
fi

cat << EOF > "$SETENV_FILE"
#!/usr/bin/env bash

# ########################################
# # Environment configuration of MDE4CPP #
# # Generated by generate_setenv.sh      #
# ########################################

export MDE4CPP_HOME="$PROJECT_DIR"

EOF

if [ "$OS_DIR" = "MacOS" ]; then
    JAVA_HOME_PATH=$(/usr/libexec/java_home -v "$JAVA_MAJOR" 2>/dev/null || echo "/opt/homebrew/opt/openjdk@$JAVA_MAJOR")
    cat << EOF >> "$SETENV_FILE"
export JAVA_HOME="$JAVA_HOME_PATH"
export CC="gcc-$GCC_MAJOR"
export CXX="g++-$GCC_MAJOR"

# Fix for gcc on newer macOS versions where it incorrectly infers an unsupported deployment target
MAC_VERSION=\$(sw_vers -productVersion | cut -d. -f1)
if [ "\$MAC_VERSION" -gt 14 ]; then MAC_VERSION=14; fi
export MACOSX_DEPLOYMENT_TARGET="\$MAC_VERSION.0"

# On macOS, Eclipse plugins are located inside Eclipse.app/Contents/Eclipse
export MDE4CPP_ECLIPSE_HOME="$ECLIPSE_DIR/Eclipse.app/Contents/Eclipse"
export PATH="\$MDE4CPP_ECLIPSE_HOME/../../../MacOS:\$PATH"
export LD_LIBRARY_PATH="\$LD_LIBRARY_PATH:\$MDE4CPP_HOME/application/bin"
EOF
else
    cat << EOF >> "$SETENV_FILE"
# resolve JAVA_HOME if javac is available
if command -v javac >/dev/null 2>&1; then
    export JAVA_HOME="\$(dirname "\$(dirname "\$(readlink -f "\$(command -v javac)")")")"
fi

export MDE4CPP_ECLIPSE_HOME="$ECLIPSE_DIR"
EOF
fi

cat << EOF >> "$SETENV_FILE"
export PATH="\$MDE4CPP_HOME/application/bin:\$MDE4CPP_HOME/application/tools:\$PATH"

# ##################################################
# # configure Gradle tasks and compiling processes #
# ##################################################

export GRADLE_OPTS="-Dorg.gradle.parallel=${GRADLE_PARALLEL:-true}"
export ORG_GRADLE_PROJECT_WORKER="${WORKER_COUNT:-1}"
export ORG_GRADLE_PROJECT_RELEASE=1
export ORG_GRADLE_PROJECT_DEBUG=1
export ORG_GRADLE_PROJECT_DEBUG_MESSAGE_FUML=0

# #############################################################################
# # Configure JAVA CLASSPATH                                                  #
# #############################################################################

export CLASSPATH="\$MDE4CPP_ECLIPSE_HOME/plugins"

# ##############################################################################
# # configure compiler information for include path setting inside cpp eclipse #
# ##############################################################################

export CPP_IDE_EXECUTABLE="\$MDE4CPP_ECLIPSE_HOME"
EOF

chmod +x "$SETENV_FILE"
echo "${C_PURPLE}[generate_setenv]${C_SUCCESS} setenv.sh generated successfully.${C_RESET}"
