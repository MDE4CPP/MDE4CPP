void PSCS_LinkEndImpl::load(std::shared_ptr<persistence::interfaces::XLoadHandler> loadHandler)
{
	std::map<std::string, std::string> attr_list = loadHandler->getAttributeList();
	loadAttributes(loadHandler, attr_list);

	//
	// Create new objects (from references (containment == true))
	//
	// get PSCSFactory
	int numNodes = loadHandler->getNumOfChildNodes();
	for(int ii = 0; ii < numNodes; ii++)
	{
		loadNode(loadHandler->getNextNodeName(), loadHandler);
	}
}		

void PSCS_LinkEndImpl::loadAttributes(std::shared_ptr<persistence::interfaces::XLoadHandler> loadHandler, std::map<std::string, std::string> attr_list)
{
	try
	{
		std::map<std::string, std::string>::const_iterator iter;
	
		iter = attr_list.find("kind");
		if ( iter != attr_list.end() )
		{
			PSCS::Semantics::StructuredClassifiers::CS_LinkKind value = PSCS::Semantics::StructuredClassifiers::CS_LinkKind::UNKNOWN;
			std::string literal = iter->second;
						if (literal == "ToEnvironment")
			{
				value = PSCS::Semantics::StructuredClassifiers::CS_LinkKind::TOENVIRONMENT;
			}
			else 			if (literal == "ToInternal")
			{
				value = PSCS::Semantics::StructuredClassifiers::CS_LinkKind::TOINTERNAL;
			}
			else 			if (literal == "None")
			{
				value = PSCS::Semantics::StructuredClassifiers::CS_LinkKind::NONE;
			}
			else 			if (literal == "Unknown")
			{
				value = PSCS::Semantics::StructuredClassifiers::CS_LinkKind::UNKNOWN;
			}
			this->setKind(value);
		}
	}
	catch (std::exception& e)
	{
		std::cout << "| ERROR    | " << e.what() << std::endl;
	}
	catch (...) 
	{
		std::cout << "| ERROR    | " <<  "Exception occurred" << std::endl;
	}

	fUML::MDE4CPP_Extensions::FUML_LinkEndImpl::loadAttributes(loadHandler, attr_list);
}

