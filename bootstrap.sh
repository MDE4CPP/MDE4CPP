#!/usr/bin/env bash
# Main bootstrap script for MDE4CPP

set -e

DIR="$( cd "$( dirname "${BASH_SOURCE[0]}" )" && pwd )"
PROJECT_DIR="$DIR"

source "$DIR/bootstrap/common.sh"
PROPS_FILE="$DIR/versions.properties"
load_properties "$PROPS_FILE"

OS="$(uname -s)"
OS_DIR=""
case "$OS" in
    Linux*)     
        echo "Detected OS: Linux"
        OS_DIR="Linux"
        ;;
    Darwin*)    
        echo "Detected OS: Mac OS"
        OS_DIR="MacOS"
        ;;
    CYGWIN*|MINGW*|MSYS*) 
        echo "Detected OS: Windows"
        if [ -f "$DIR/bootstrap/Windows/bootstrap.bat" ]; then
            cmd.exe /c "$(cygpath -w "$DIR/bootstrap/Windows/bootstrap.bat")"
        else
            echo "Windows script not found."
            exit 1
        fi
        exit 0
        ;;
    *)          
        echo "Detected OS: Unknown ($OS)"
        echo "Cannot bootstrap automatically."
        exit 1
        ;;
esac

echo "==========================================================="
echo "Installing system tools for $OS_DIR..."
echo "==========================================================="

if [ "$OS_DIR" = "MacOS" ]; then
    echo "Checking Homebrew..."
    if ! command -v brew &> /dev/null; then
        echo "Homebrew not found. Installing Homebrew..."
        /bin/bash -c "$(curl -fsSL https://raw.githubusercontent.com/Homebrew/install/HEAD/install.sh)"
        eval "$(/opt/homebrew/bin/brew shellenv 2>/dev/null || /usr/local/bin/brew shellenv 2>/dev/null)"
    else
        echo "Homebrew is installed."
    fi
fi

bash "$DIR/bootstrap/unix/installJava.sh"
bash "$DIR/bootstrap/unix/installCompiler.sh"
bash "$DIR/bootstrap/unix/installCMake.sh"

export MDE4CPP_HOME="$PROJECT_DIR"
bash "$DIR/bootstrap/unix/installEclipse.sh"

echo "==========================================================="
echo "Generating setenv.sh..."
echo "==========================================================="

SETENV_FILE="$DIR/setenv.sh"
ECLIPSE_DIR="$(cd "$DIR/.." && pwd)/eclipse"
JAVA_MAJOR="${MDE4CPP_JAVA_VERSION%%.*}"
GCC_MAJOR="${MDE4CPP_COMPILER_VERSION%%.*}"

cat << EOF > "$SETENV_FILE"
#!/usr/bin/env bash

# ########################################
# # Environment configuration of MDE4CPP #
# # Generated by bootstrap.sh            #
# ########################################

export MDE4CPP_HOME="$PROJECT_DIR"

EOF

if [ "$OS_DIR" = "MacOS" ]; then
    JAVA_HOME_PATH=$(/usr/libexec/java_home -v "$JAVA_MAJOR" 2>/dev/null || echo "/opt/homebrew/opt/openjdk@$JAVA_MAJOR")
    cat << EOF >> "$SETENV_FILE"
export JAVA_HOME="$JAVA_HOME_PATH"
export CC="gcc-$GCC_MAJOR"
export CXX="g++-$GCC_MAJOR"

# On macOS, Eclipse plugins are located inside Eclipse.app/Contents/Eclipse
export MDE4CPP_ECLIPSE_HOME="$ECLIPSE_DIR/Eclipse.app/Contents/Eclipse"
export PATH="\$MDE4CPP_ECLIPSE_HOME/../../../MacOS:\$PATH"
export LD_LIBRARY_PATH="\$LD_LIBRARY_PATH:\$MDE4CPP_HOME/application/bin"
EOF
else
    cat << EOF >> "$SETENV_FILE"
# resolve JAVA_HOME if javac is available
if command -v javac >/dev/null 2>&1; then
    export JAVA_HOME="\$(dirname "\$(dirname "\$(readlink -f "\$(command -v javac)")")")"
fi

export MDE4CPP_ECLIPSE_HOME="$ECLIPSE_DIR"
EOF
fi

cat << EOF >> "$SETENV_FILE"
export PATH="\$MDE4CPP_HOME/application/bin:\$MDE4CPP_HOME/application/tools:\$PATH"

# ##################################################
# # configure Gradle tasks and compiling processes #
# ##################################################

export GRADLE_OPTS="-Dorg.gradle.parallel=true"
export ORG_GRADLE_PROJECT_WORKER=1
export ORG_GRADLE_PROJECT_RELEASE=1
export ORG_GRADLE_PROJECT_DEBUG=1
export ORG_GRADLE_PROJECT_DEBUG_MESSAGE_FUML=0

# #############################################################################
# # Configure JAVA CLASSPATH                                                  #
# #############################################################################

export CLASSPATH="\$MDE4CPP_ECLIPSE_HOME/plugins"

# ##############################################################################
# # configure compiler information for include path setting inside cpp eclipse #
# ##############################################################################

export CPP_IDE_EXECUTABLE="\$MDE4CPP_ECLIPSE_HOME"
EOF

chmod +x "$SETENV_FILE"

echo "==========================================================="
echo "Running Gradle install to download third-party dependencies..."
echo "==========================================================="

source "$SETENV_FILE"
cd "$PROJECT_DIR"

GRADLE_WRAPPER="$PROJECT_DIR/application/tools/gradlew"
if [[ -x "$GRADLE_WRAPPER" ]]; then
    set +e
    "$GRADLE_WRAPPER" install --no-daemon
    GRADLE_EXIT=$?
    set -e
    if [[ $GRADLE_EXIT -ne 0 ]]; then
        echo "ERROR: Gradle install task failed (exit $GRADLE_EXIT)"
        exit $GRADLE_EXIT
    fi
    echo "Gradle install completed successfully."
else
    echo "WARNING: Gradle wrapper not found or not executable at $GRADLE_WRAPPER, skipping Gradle install."
fi

echo "==========================================================="
echo "Bootstrap completed successfully!"
echo "To activate the environment, please run:"
echo "  source setenv.sh"
echo "==========================================================="
